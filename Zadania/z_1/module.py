'''
9.Используя замыкания функций, объявите внутреннюю функцию,
которая принимает в качестве аргумента коллекцию (список или кортеж)
и возвращает или минимальное значение, или максимальное,
в зависимости от значения параметра type внешней функции.
Если type равен «max», то возвращается максимальное значение,
иначе – минимальное. По умолчанию type должно принимать значение «max».
Вызовите внутреннюю функцию замыкания и отобразите на экране результат ее работы.
'''
def make_extremum(type="max"):
    def extremum(collection):
        if type == "max":
            return max(collection)
        else:
            return min(collection)
    return extremum
